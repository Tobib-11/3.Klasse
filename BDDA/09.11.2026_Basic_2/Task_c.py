#Verwende eine while-Schleife, um eine Variable sekunden von 3 auf 1
#herunterzuzählen und den jeweiligen Wert in jeder Iteration auszugeben.
#Die Schleife soll stoppen, sobald sekunden den Wert 0 erreicht (die 0
#selbst soll nicht mehr ausgegeben werden)


sek = 3
while sek > 0:
    print(sek)
    sek -= 1
print('Fertig')
